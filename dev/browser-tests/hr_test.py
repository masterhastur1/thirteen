import asyncio, subprocess, time, os
from playwright.async_api import async_playwright
S=os.path.dirname(os.path.abspath(__file__))
ROOT=os.path.abspath(os.path.join(S,'..','..'))   # the built app (run build.py first)
SERVER=os.environ.get('THIRTEEN_SERVER',os.path.join(ROOT,'..','thirteen-server'))
os.makedirs(S+'/out',exist_ok=True)
web=subprocess.Popen(['python3','-m','http.server','8098','-d',ROOT],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
async def main():
    time.sleep(1)
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
        ctx=await b.new_context(viewport={'width':390,'height':800},device_scale_factor=2); pg=await ctx.new_page(); errs=[]
        pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto('http://127.0.0.1:8098/index.html'); await pg.wait_for_timeout(800)
        await pg.evaluate("show('settings')"); await pg.wait_for_timeout(200)
        print('button hidden before:', await pg.evaluate("$('#btn-hands').hidden"))
        await pg.click('#chart-switch'); await pg.wait_for_timeout(200)
        await pg.screenshot(path=S+'/out/hr_settings.png')
        await pg.evaluate("showRules()"); await pg.wait_for_timeout(300)
        await pg.evaluate("document.querySelector('#rl-hands').scrollIntoView({block:'center'})"); await pg.screenshot(path=S+'/out/hr_rules.png')
        await pg.click('#rl-hands'); await pg.wait_for_timeout(300); await pg.screenshot(path=S+'/out/hr_chart.png')
        await pg.click('#hr-x'); await pg.evaluate("closeSheet()")
        await pg.evaluate("newMatch(); show('game'); deal()"); await pg.wait_for_timeout(3500)
        await pg.screenshot(path=S+'/out/hr_game.png')
        await pg.click('#btn-hands'); await pg.wait_for_timeout(300); print('chart open in game:', await pg.evaluate("!$('#hrank').hidden"))
        await pg.click('#hr-x')
        await pg.set_viewport_size({'width':844,'height':390}); await pg.wait_for_timeout(600)
        await pg.screenshot(path=S+'/out/hr_land.png')
        await pg.click('#btn-hands'); await pg.wait_for_timeout(300); await pg.screenshot(path=S+'/out/hr_land_chart.png')
        print('reload keeps setting:', await pg.evaluate("JSON.parse(localStorage.getItem('thirteen.settings')).chart"))
        print('errors:', errs)
        await b.close()
try: asyncio.run(main())
finally: web.terminate()
